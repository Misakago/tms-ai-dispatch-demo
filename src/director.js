import { ctl, W, H } from './Stage.jsx'

const sleep = (ms) => new Promise((r) => setTimeout(r, ms))

// 一句字幕：显示后至少停留 hold 毫秒（按字数估算阅读时长）
async function say(text, sub, hold) {
  ctl.caption(text, sub)
  await sleep(hold ?? Math.max(2000, 700 + text.length * 112))
}

async function chapter(no, line, icon, title, sub, progress) {
  ctl.caption(null)
  await ctl.cursorShow(false)
  ctl.chapterOn({ no, line, icon, title, sub })
  ctl.setProgress(progress)
  await sleep(2300)
  ctl.chapterOff()
  await sleep(450)
}

